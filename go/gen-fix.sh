#!/usr/bin/env bash
# Generate the fix for kubernetes/kubernetes#144077 from the Lean specification.
#
#   1. build `gofix` (ApfQueueSet/Synth.lean, ApfQueueSet/GoFixMain.lean)
#   2. `gofix naive` spliced into queueset.go must leave the pinned upstream file
#      unchanged, byte for byte. This checks the generator's template and the
#      observation table against the code that is really there.
#   3. `gofix strict` spliced into queueset.go, gofmt'd, is the fix. Its diff is
#      written to go/patches/0003-fix-from-spec.patch.
#   4. the resulting file is compared with the file PR #144078 produces (0001).
#
# Exit 0 only if 2 holds and the generated file is gofmt-clean. Step 4 is reported.
# With --check, also fail if the committed 0003 patch differs from the regenerated one.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(dirname "$HERE")"
UP="$HERE/upstream"
REL=staging/src/k8s.io/apiserver/pkg/util/flowcontrol/fairqueuing/queueset/queueset.go
FN='func (qs *queueSet) removeQueueIfEmptyLocked('
OUT="$HERE/patches/0003-fix-from-spec.patch"
CHECK="${1:-}"

"$HERE/fetch.sh" >/dev/null
( cd "$ROOT" && lake build gofix >/dev/null )
GOFIX="$ROOT/.lake/build/bin/gofix"
restore() { git -C "$UP" reset -q; git -C "$UP" checkout -q .; git -C "$UP" clean -fdq; }
restore
trap restore EXIT
TMP="$(mktemp -d)"

# 2. naive reading regenerates upstream
"$GOFIX" naive | uv run "$HERE/splice.py" "$UP/$REL" "$FN"
if git -C "$UP" diff --quiet; then
  echo "naive reading: regenerates the upstream function byte for byte"
else
  echo "naive reading: DIFFERS from upstream"; git -C "$UP" diff | head -40; exit 1
fi

# 3. strict reading is the fix
"$GOFIX" strict | uv run "$HERE/splice.py" "$UP/$REL" "$FN"
if [ -n "$(gofmt -l "$UP/$REL")" ]; then echo "generated file is not gofmt-clean"; exit 1; fi
cp "$UP/$REL" "$TMP/generated.go"
{
  cat <<HDR
From: generated by go/gen-fix.sh from ApfQueueSet/Synth.lean (\`gofix strict\`)
Subject: apiserver/flowcontrol: removeQueueIfEmptyLocked, guard derived from the strict reading of "empty"

Provenance: machine-generated. The condition is \`derive strictReading\` printed as Go; the rest of the
function is the upstream text. Do not edit by hand, run go/gen-fix.sh.
Applies to dbe731cf4b0286d68d743068f251263c70719f3e. Addresses https://github.com/kubernetes/kubernetes/issues/144077.

HDR
  git -C "$UP" diff --no-color
} > "$TMP/0003.patch"
echo "strict reading: $(git -C "$UP" diff --numstat | awk '{print "+"$1" -"$2}') lines in queueset.go"

# 4. compare with PR #144078
restore
git -C "$UP" apply "$HERE/patches/0001-fix-144078.patch"
if cmp -s "$UP/$REL" "$TMP/generated.go"; then
  echo "generated queueset.go is byte-identical to queueset.go with PR #144078 applied"
else
  echo "generated queueset.go differs from PR #144078's:"; diff "$UP/$REL" "$TMP/generated.go" | head -20
fi

if [ "$CHECK" = "--check" ]; then
  # the diff body must match; the index line depends on nothing local
  cmp -s "$OUT" "$TMP/0003.patch" || { echo "committed $OUT is stale, run go/gen-fix.sh"; exit 1; }
  echo "committed 0003 patch is up to date"
else
  cp "$TMP/0003.patch" "$OUT"
  echo "wrote $OUT"
fi
